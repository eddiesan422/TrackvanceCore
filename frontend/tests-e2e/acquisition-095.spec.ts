test('REST real: reserva concurrente → cancelar espera → reutilizar nombre → conservar v1/v2 ante fallo; recuperación nativa coordinada', async ({ page, context }, info) => {
  test.setTimeout(600_000)
  const started = Date.now(), nonce = randomBytes(6).toString('hex')
  const internal = process.env.TV_CORE095_DOCUMENT_RECEIVER_URL || '', control = process.env.TV_CORE095_DOCUMENT_RECEIVER_CONTROL_URL || ''
  expect(internal.startsWith('http://document-fixture:18095') || internal.startsWith('http://rest-fixture:18090')).toBe(true)
  expect(['127.0.0.1', 'localhost']).toContain(new URL(control).hostname)
  const fixturePath = `/acquisition/${nonce}`, restartDirectory = process.env.TV_CORE095_RESTART_CONTROL_DIR || ''
  const retryWait = restartDirectory ? 30 : 5
  await login(page)
  await page.goto('/connections')
  await page.getByRole('button', { name: 'Nueva conexión REST', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Nueva conexión REST', exact: true })
  await dialog.getByLabel('Nombre', { exact: true }).fill(`A095 recovery source ${nonce}`)
  await dialog.getByLabel('URL del endpoint', { exact: true }).fill(internal + fixturePath + '/source')
  await dialog.getByLabel('Paginación', { exact: true }).selectOption('PAGE')
  await dialog.getByLabel('Filas por página', { exact: true }).fill('2')
  await dialog.getByLabel('Reintentos adicionales (0–5)', { exact: true }).fill('3')
  await dialog.getByLabel('Espera entre reintentos (segundos)', { exact: true }).fill(String(retryWait))
  await dialog.getByLabel('Tiempo máximo total de adquisición (segundos)', { exact: true }).fill('180')
  await dialog.getByRole('button', { name: 'Probar lectura GET', exact: true }).click()
  await expect(dialog.getByText('Prueba de acceso completada con la configuración actual.', { exact: true })).toBeVisible()
  const connectionResponse = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/connections')
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
  const connectionHttp = await connectionResponse
  expect(connectionHttp.status()).toBe(201)
  const connection = await connectionHttp.json()
  await page.waitForURL(new RegExp(`/connections/${connection.id}$`))
  await expect(page.getByRole('table', { name: 'Vista previa de la fuente' }).locator('tbody tr')).toHaveCount(3)
  const competing = await context.newPage()
  await competing.goto(`/connections/${connection.id}`)
  await expect(competing.getByRole('table', { name: 'Vista previa de la fuente' }).locator('tbody tr')).toHaveCount(3)
  const name = `A095 reserved ${nonce}`
  await page.getByLabel('Nombre del dataset', { exact: true }).fill(name)
  await competing.getByLabel('Nombre del dataset', { exact: true }).fill(name)
  expect((await page.request.post(control + fixturePath + '/arm', { data: { failures: 8 } })).status()).toBe(201)
  const isRegistration = (r: { request: () => { method: () => string }; url: () => string }) => r.request().method() === 'POST' && new URL(r.url()).pathname === `/api/v1/connections/${connection.id}/acquisitions`
  const responses = [page.waitForResponse(isRegistration), competing.waitForResponse(isRegistration)]
  await Promise.all([page, competing].map(surface => surface.getByRole('button', { name: 'Crear dataset y adquirir fuente', exact: true }).click()))
  const [first, second] = await Promise.all(responses)
  expect([first.status(), second.status()].sort()).toEqual([202, 409])
  const winner = first.status() === 202 ? page : competing, loser = first.status() === 202 ? competing : page
  const initial = await (first.status() === 202 ? first : second).json()
  expect(initial.dataset).toBeNull()
  expect(initial.acquisition.dataset_id).toBeNull()
  await expect(loser.getByRole('alert')).toContainText('nombre')
  await expect(winner.getByText(/Reintentando en/).first()).toBeVisible({ timeout: 30_000 })
  await winner.getByRole('button', { name: 'Cancelar adquisición', exact: true }).click()
  await expect.poll(async () => (await (await winner.request.get(`/api/v1/acquisitions/${initial.acquisition.id}`)).json()).status, { timeout: 30_000 }).toBe('CANCELLED')
  const cancelled = await (await winner.request.get(`/api/v1/acquisitions/${initial.acquisition.id}`)).json()
  expect(cancelled.dataset_id).toBeNull()
  expect(cancelled.output_version_id).toBeNull()
  const stoppedReceipt = await (await winner.request.get(control + fixturePath + '/receipt')).json()
  await winner.waitForTimeout((retryWait + 1) * 1000)
  expect((await (await winner.request.get(control + fixturePath + '/receipt')).json()).calls).toEqual(stoppedReceipt.calls)
  expect((await winner.request.post(control + fixturePath + '/faults', { data: { failures: 0 } })).status()).toBe(200)
  await loser.close()
  await winner.getByRole('button', { name: 'Corregir selección e intentar de nuevo', exact: true }).click()
  await expect(winner.getByLabel('Nombre del dataset', { exact: true })).toHaveValue(name)
  const reusedResponse = winner.waitForResponse(isRegistration)
  await winner.getByRole('button', { name: 'Crear dataset y adquirir fuente', exact: true }).click()
  const reusedHttp = await reusedResponse
  expect(reusedHttp.status()).toBe(202)
  const reused = await reusedHttp.json()
  expect(reused.acquisition.id).not.toBe(initial.acquisition.id)
  await expect(winner.getByRole('link', { name: 'Ver dataset', exact: true })).toBeVisible({ timeout: 90_000 })
  const successful = await (await winner.request.get(`/api/v1/acquisitions/${reused.acquisition.id}`)).json()
  expect(successful.status).toBe('SUCCESS')
  await winner.getByRole('link', { name: 'Ver dataset', exact: true }).click()
  await expect(winner.getByRole('heading', { name, exact: true })).toBeVisible()
  await winner.getByRole('button', { name: 'Nueva versión desde la fuente', exact: true }).click()
  await expect(winner.getByRole('link', { name: 'Comparar versiones', exact: true })).toBeVisible({ timeout: 90_000 })
  const before = await (await winner.request.get(`/api/v1/datasets/${successful.dataset_id}`)).json()
  expect(before.versions).toHaveLength(2)
  const preserved = before.versions.map((version: { id: string; sha256: string; schema_hash: string; row_count: number }) => ({ id: version.id, sha256: version.sha256, schema_hash: version.schema_hash, row_count: version.row_count }))
  expect((await winner.request.post(control + fixturePath + '/faults', { data: { failures: 8 } })).status()).toBe(200)
  const failedResponse = winner.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === `/api/v1/datasets/${successful.dataset_id}/acquisitions/refresh`)
  await winner.getByRole('button', { name: 'Nueva versión desde la fuente', exact: true }).click()
  const failedHttp = await failedResponse
  expect(failedHttp.status()).toBe(202)
  const failedRun = await failedHttp.json()
  await expect(winner.getByText(/Reintentando en/).first()).toBeVisible({ timeout: 30_000 })
  await expect(winner.getByText('No se publicó una versión parcial.', { exact: false }).first()).toBeVisible({ timeout: 150_000 })
  const failed = await (await winner.request.get(`/api/v1/acquisitions/${failedRun.id}`)).json()
  expect(failed.status).toBe('FAILED')
  expect(failed.error_code).toBe('REST_RETRIES_EXHAUSTED')
  expect(failed.output_version_id).toBeNull()
  const after = await (await winner.request.get(`/api/v1/datasets/${successful.dataset_id}`)).json()
  expect(after.versions.map((version: { id: string; sha256: string; schema_hash: string; row_count: number }) => ({ id: version.id, sha256: version.sha256, schema_hash: version.schema_hash, row_count: version.row_count }))).toEqual(preserved)
  let restartEvidence: Record<string, unknown> = { executed: false, reason: 'No native worker-control handshake requested; the CI case does not claim restart coverage.' }
  if (restartDirectory) {
    expect(process.env.TV_CORE095_TEST_PROJECT).toBe('trackvance-codex')
    expect(isAbsolute(restartDirectory)).toBe(true)
    expect((await winner.request.post(control + fixturePath + '/faults', { data: { failures: 1 } })).status()).toBe(200)
    const recoveryResponse = winner.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === `/api/v1/datasets/${successful.dataset_id}/acquisitions/refresh`)
    await winner.getByRole('button', { name: 'Nueva versión desde la fuente', exact: true }).click()
    const recoveryHttp = await recoveryResponse
    expect(recoveryHttp.status()).toBe(202)
    const recovery = await recoveryHttp.json()
    await expect(winner.getByText(/Reintentando en/).first()).toBeVisible({ timeout: 30_000 })
    const running = await (await winner.request.get(`/api/v1/acquisitions/${recovery.id}`)).json()
    expect(running.retry_state.status).toBe('WAITING')
    await mkdir(restartDirectory, { recursive: true })
    await writeFile(join(restartDirectory, `${nonce}-ready.json`), JSON.stringify({ acquisition_id: recovery.id, nonce, worker_role: 'acquisition-worker' }))
    let receipt: Record<string, unknown> | null = null
    await expect.poll(async () => {
      try { receipt = JSON.parse(await readFile(join(restartDirectory, `${nonce}-restart-receipt.json`), 'utf8')); return receipt?.status }
      catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null; throw error }
    }, { timeout: 120_000, intervals: [500] }).toBe('PASS')
    expect(receipt!.acquisition_id).toBe(recovery.id)
    expect(receipt!.worker_role).toBe('acquisition-worker')
    expect(receipt!.stop_receipt_sha256).toMatch(/^[a-f0-9]{64}$/)
    expect(receipt!.start_receipt_sha256).toMatch(/^[a-f0-9]{64}$/)
    await expect.poll(async () => (await (await winner.request.get(`/api/v1/acquisitions/${recovery.id}`)).json()).status, { timeout: 180_000, intervals: [1000] }).toBe('SUCCESS')
    const recovered = await (await winner.request.get(`/api/v1/acquisitions/${recovery.id}`)).json()
    expect(recovered.id).toBe(recovery.id)
    expect(recovered.started_at).toBe(running.started_at)
    expect(recovered.attempts).toBeGreaterThanOrEqual(2)
    expect(recovered.dataset_id).toBe(successful.dataset_id)
    const completed = await (await winner.request.get(`/api/v1/datasets/${successful.dataset_id}`)).json()
    expect(completed.versions).toHaveLength(3)
    expect(completed.versions.filter((version: { id: string }) => version.id === recovered.output_version_id)).toHaveLength(1)
    restartEvidence = { executed: true, acquisition_id: recovery.id, attempts: recovered.attempts, started_at: recovered.started_at, guard_receipt: receipt }
  }
  await info.attach('acquisition-095-native-failure-evidence.json', { body: JSON.stringify({ nonce, connection_id: connection.id,
    concurrent_statuses: [first.status(), second.status()], cancelled_acquisition_id: initial.acquisition.id, cancelled_source_receipt: stoppedReceipt,
    successful_acquisition_id: reused.acquisition.id, dataset_id: successful.dataset_id, failed_acquisition_id: failedRun.id,
    preserved_versions: preserved, retry_failure_code: failed.error_code, restart: restartEvidence, elapsed_seconds: (Date.now() - started) / 1000 }), contentType: 'application/json' })
})
